/**
 * Правила приглашения по ссылке: длина токена, адрес страницы и то, чем ссылка
 * заканчивается для открывшего.
 *
 * Отдельно от запросов — это политика, и проверяется она тестом. Страница
 * приглашения и действие «присоединиться» спрашивают её об одном и том же:
 * иначе на экране оказалась бы кнопка, на которую действие отвечает отказом.
 */

/**
 * Шестнадцать байт — 128 бит случайности: подобрать нельзя, а ссылка остаётся
 * короткой. Короткая здесь важнее, чем у ссылки из письма: эту кидают в чат,
 * пересылают и иногда диктуют вслух.
 */
export const INVITE_TOKEN_BYTES = 16;

/** Адрес страницы приглашения. */
export function invitePath(token: string): string {
  return `/join/${encodeURIComponent(token)}`;
}

/** Чем ссылка оборачивается для того, кто её открыл. */
export type InviteOutcome =
  /** Можно присоединиться. */
  | "join"
  /** Открывший уже в поездке — ссылка для него просто короткий путь. */
  | "member"
  /** Поездка завершена: приходить в неё поздно, она закрыта на запись. */
  | "completed"
  /** Ссылки нет: её отозвали, выпустили новую или поездки больше нет. */
  | "broken";

export interface InviteSituation {
  tripStatus: "ACTIVE" | "COMPLETED";
  /** Открывший ссылку уже участвует в этой поездке. */
  viewerIsMember: boolean;
}

export function inviteOutcome(situation: InviteSituation | null): InviteOutcome {
  if (!situation) return "broken";
  // Участие проверяется раньше статуса: своя поездка открывается и завершённой —
  // отказывать её же участнику из-за завершения было бы странно.
  if (situation.viewerIsMember) return "member";
  if (situation.tripStatus === "COMPLETED") return "completed";
  return "join";
}

/**
 * Отказы называются одинаково на странице и в действии: человек не должен
 * увидеть одно объяснение до нажатия и другое после.
 */
export const INVITE_BROKEN = "Ссылка не работает: её отозвали или поездки больше нет";
export const INVITE_COMPLETED = "Поездка уже завершена — присоединяться к ней поздно";
