/**
 * Набор аватарок.
 *
 * Картинку не загружают, а выбирают из готового списка: приложению не нужно
 * ни хранилище файлов, ни пережатие картинок, ни выдача пользовательского
 * содержимого — а поездке хватает того, чтобы участники различались в списке.
 *
 * Рисунки лежат здесь строками путей, а не файлами: набор весит пару килобайт,
 * не зависит от статики и рисуется в любом размере. Стиль один на все — контур
 * в квадрате 24×24, поэтому компоненту достаточно одного способа отрисовки.
 */
export interface AvatarPreset {
  id: string;
  /** Подпись для выбора и для `alt`: рисунок должен называться словом. */
  label: string;
  color: string;
  paths: string[];
}

