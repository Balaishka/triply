const BY_ID = new Map(AVATAR_PRESETS.map((preset) => [preset.id, preset]));

/**
 * Аватарка по идентификатору из базы.
 *
 * Неизвестное значение — не ошибка, а повод показать инициалы: набор со
 * временем меняется, а строки в базе остаются от прежнего.
 */
export function avatarById(id: string | null | undefined): AvatarPreset | undefined {
  return id ? BY_ID.get(id) : undefined;
}

/** Проверка выбора перед записью в базу. */
export function isAvatarId(value: unknown): value is string {
  return typeof value === "string" && BY_ID.has(value);
}
