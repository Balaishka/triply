import { createHash, randomBytes } from "node:crypto";

/**
 * Случайный секрет, который живёт у пользователя: токен сессии, ссылка из
 * письма, приглашение в поездку.
 *
 * По умолчанию 256 бит — столько же, сколько у ключа от аккаунта. Приглашению
 * хватает половины: оно открывает одну поездку, зато его пересылают в чате, а
 * иногда и диктуют, и лишние символы там дороже.
 */
export function randomToken(bytes = 32): string {
  return randomBytes(bytes).toString("base64url");
}

/**
 * Хеш секрета для хранения в базе: так лежат токен сессии и ссылки из писем —
 * дамп не должен давать вход.
 *
 * Токен случайный, поэтому хеш без соли здесь достаточен — перебирать нечего.
 * Быстрый SHA-256 при этом позволяет искать запись по хешу обычным уникальным
 * индексом.
 */
export function hashToken(token: string): string {
  return createHash("sha256").update(token).digest("hex");
}
