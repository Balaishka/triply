/**
 * Куда вернуть человека после входа или регистрации.
 *
 * Приглашение в поездку открывают и без сессии: по ссылке из чата приходит в том
 * числе тот, у кого аккаунта ещё нет. Чтобы поездка не потерялась по дороге через
 * вход, её адрес едет следом параметром `next`.
 *
 * Параметр приходит из адресной строки, то есть от кого угодно, поэтому наружу
 * он не пускается: `//чужой.сайт` и `https://чужой.сайт` браузер считает другим
 * сайтом, и переход туда сразу после входа — обычный способ увести человека на
 * поддельную форму.
 */
export const DEFAULT_AFTER_LOGIN = "/";

export function safeNextPath(value: unknown): string {
  if (typeof value !== "string") return DEFAULT_AFTER_LOGIN;

  const path = value.trim();
  if (!path.startsWith("/")) return DEFAULT_AFTER_LOGIN;

  // Второй символ решает всё: `//` и `/\` браузер читает как адрес чужого сайта
  // со схемой текущей страницы.
  if (path.startsWith("//") || path.startsWith("/\\")) return DEFAULT_AFTER_LOGIN;

  // Пробелы и управляющие символы в пути не нужны, зато помогают обойти проверку
  // выше: перевод строки в середине адреса браузеры просто выбрасывают.
  if ([...path].some((char) => char.charCodeAt(0) <= 32)) {
    return DEFAULT_AFTER_LOGIN;
  }

  return path;
}
